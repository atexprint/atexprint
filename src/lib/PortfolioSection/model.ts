export function preloadPortfolioMedia(): void {
	for (const item of PORTFOLIO_ITEMS) {
		for (const m of item.media) {
			if (m.type === 'img') {
				const img = new Image();
				img.src = m.url;
			} else if (m.type === 'video') {
				const link = document.createElement('link');
				link.rel = 'preload';
				link.as = 'video';
				link.href = m.url;
				document.head.appendChild(link);
			}
		}
	}
}
