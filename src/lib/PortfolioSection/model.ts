const mediaCache = new Map<string, string>();

async function cacheMediaUrl(url: string): Promise<void> {
	if (mediaCache.has(url)) return;
	try {
		const response = await fetch(url);
		const blob = await response.blob();
		mediaCache.set(url, URL.createObjectURL(blob));
	} catch {
		// Fall back to original URL on failure
	}
}

export function getCachedUrl(url: string): string {
	return mediaCache.get(url) ?? url;
}

export function preloadPortfolioMedia(): void {
	for (const item of PORTFOLIO_ITEMS) {
		for (const m of item.media) {
			cacheMediaUrl(m.url);
		}
		cacheMediaUrl(item.image);
	}
}
